def tr(lang, key, *args):
    code = lang if lang in TEXT else "pt"
    text = TEXT[code].get(key) or TEXT["pt"].get(key) or key
    if args:
        return text % args
    return text


def date_line(lang, wday, day, month):
    code = lang if lang in WEEKDAYS else "pt"
    return tr(code, "date", WEEKDAYS[code][wday], day, MONTHS[code][month - 1])


def code_of(name):
    for code, label in NAMES.items():
        if label == name:
            return code
    return "pt"
